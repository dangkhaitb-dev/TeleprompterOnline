// 🚀 AUTO-DETECT ALL HTML PAGES
function generateInputEntries() {
  const root = process.cwd()
  const pagesDir = resolve(root, 'pages')
  const blogDir = resolve(root, 'blog')

  const inputs = {
    main: resolve(root, 'index.html'),
  }

  // Root-level HTML files generated by 11ty (about.html, contact.html, etc.)
  readdirSync(root, { withFileTypes: true })
    .filter(f => f.isFile() && f.name.endsWith('.html') && f.name !== 'index.html')
    .forEach(f => {
      const name = f.name.replace('.html', '')
      inputs[name] = resolve(root, f.name)
      console.log(`📄 Auto-detected root: ${f.name}`)
    })

  // Clean nested article routes: blog/<slug>/index.html
  if (existsSync(blogDir)) {
    readdirSync(blogDir, { withFileTypes: true })
      .filter(item => item.isDirectory())
      .forEach(item => {
        const indexFile = resolve(blogDir, item.name, 'index.html')
        if (existsSync(indexFile)) {
          inputs[`blog-${item.name}`] = indexFile
          console.log(`📝 Auto-detected article: blog/${item.name}/index.html`)
        }
      })
  }

  // pages/lang/index.html entries
  if (existsSync(pagesDir)) {
    readdirSync(pagesDir, { withFileTypes: true })
      .filter(item => item.isDirectory())
      .forEach(item => {
        const indexFile = resolve(pagesDir, item.name, 'index.html')
        if (existsSync(indexFile)) {
          inputs[`${item.name}-index`] = indexFile
          console.log(`🌍 Auto-detected: ${item.name}/index.html`)
        }
      })
  }

  return inputs
}

// 🌐 URL REWRITING FUNCTION (handles both dev and preview servers)
function rewriteUrl(url, isDev = true) {
  const prefix = isDev ? '/pages' : ''

  // Parse URL to get pathname (strip query string for matching)
  const [pathname, query] = url.split('?')
  const qs = query ? `?${query}` : ''

  // Skip if already has extension (images, css, js, etc.)
  if (/\.\w{2,5}$/.test(pathname)) return url

  // Auto-detect root-level HTML pages (workspaces, teleprompter, etc.)
  const root = process.cwd()

  // Resolve extensionless nested pages before checking root-level aliases.
  const cleanPathname = pathname.replace(/^\/+|\/+$/g, '')
  if (cleanPathname) {
    const nestedIndex = resolve(root, cleanPathname, 'index.html')
    if (nestedIndex.startsWith(`${root}/`) && existsSync(nestedIndex)) {
      return `/${cleanPathname}/index.html${qs}`
    }
  }

  const rootHtmlFiles = readdirSync(root, { withFileTypes: true })
    .filter(f => f.isFile() && f.name.endsWith('.html') && f.name !== 'index.html')
    .map(f => f.name.replace('.html', ''))

  for (const page of rootHtmlFiles) {
    if (pathname === `/${page}` || pathname === `/${page}/`) {
      return `/${page}.html${qs}`
    }
  }

  // Auto-detect language folders
  const pagesDir = resolve(process.cwd(), 'pages')
  if (existsSync(pagesDir)) {
    const langs = readdirSync(pagesDir, { withFileTypes: true })
      .filter(i => i.isDirectory())
      .map(i => i.name)
    for (const lang of langs) {
      if (pathname === `/${lang}` || pathname === `/${lang}/`) {
        return `${prefix}/${lang}/index.html${qs}`
      }
    }
  }

  return url
}

// Deduplicate external <script> tags in HTML (Rollup emits a bare import for
// every chunk that transitively depends on an external module, causing Vite to
// emit duplicate <script> tags — browsers already deduplicate via the module map).
const deduplicateExternalScripts = {
  name: 'deduplicate-external-scripts',
  transformIndexHtml(html) {
    const seen = new Set();
    return html.replace(/<script[^>]+src="(https?:\/\/[^"]+)"[^>]*><\/script>/g, (match, src) => {
      if (seen.has(src)) return '';
      seen.add(src);
      return match;
    });
  },
};

export default defineConfig({
  // Inject build-time constants
  define: {
    '__SW_VERSION__': JSON.stringify(Date.now()), // Build timestamp for cache busting
  },
  server: {
    hmr: false, // Disable WebSocket HMR - prevents ERR_SOCKET_NOT_CONNECTED errors
    open: true, // Auto-open in system default browser
  },
  plugins: [
    deduplicateExternalScripts,
    // Custom URL rewriting plugin for dev and preview servers
    {
      name: 'dev-url-rewriter',
      configureServer(server) {
        server.middlewares.use((req, _res, next) => {
          req.url = rewriteUrl(req.url, true)
          next()
        })
      },
      configurePreviewServer(server) {
        server.middlewares.use((req, _res, next) => {
          req.url = rewriteUrl(req.url, false)
          next()
        })
      }
    },
    minifyHTML(),
    htmlMinifier({
      minify: {
        collapseWhitespace: true,
        conservativeCollapse: true,
        removeComments: true,
        keepClosingSlash: true,
        removeRedundantAttributes: false,
        removeEmptyAttributes: false,
        removeOptionalTags: false,
        minifyCSS: false,
        minifyJS: true
      }
    }),
    // Inject modulepreload for critical JS (eliminates waterfall)
    modulePreload(),
    // Move CSS links before scripts to reduce LCP render delay
    cssPreload(),
    // Run PurgeCSS before inlining critical CSS for smaller inline
    purgeCss({
      content: [
        './*.html',
        './blog/**/*.html',
        './src/**/*.{js,ts,jsx,tsx,html}'
      ],
      // Custom extractor to also find data-* attribute values from JS
      defaultExtractor: content => {
        // Standard class/id extraction (Tailwind-style)
        const standard = content.match(/[\w-/:]+(?<!:)/g) || [];
        // Extract data-* attribute values from JS: dataset.foo = 'bar' → data-foo="bar"
        const datasetMatches = content.match(/\.dataset\.(\w+)\s*=\s*['"]([^'"]+)['"]/g) || [];
        const dataAttrs = datasetMatches.map(m => {
          const match = m.match(/\.dataset\.(\w+)\s*=\s*['"]([^'"]+)['"]/);
          if (match) {
            const attr = match[1].replace(/([A-Z])/g, '-$1').toLowerCase();
            return `data-${attr}="${match[2]}"`;
          }
          return null;
        }).filter(Boolean);
        return [...standard, ...dataAttrs];
      },
      safelist: {
        standard: [
          /^nav/, /^navbar/, /^drawer/,
          /^btn/, /^button/,
          /^modal/, /^overlay/,
          /^hero/, /^section/, /^card/,
          'active', 'open', 'loading', 'error', 'visible', 'hidden',
          'no-scroll',
          /^md-sys/,
          /^text/, /^grid/, /^rounded/, /^surface/,
          /--hover/, /--focus/, /--active/, /--visible/, /--hidden/,
          /ThemeIconSun$/, /ThemeIconMoon$/,
        ],
        greedy: [
          /\[data-/, // preserve all [data-*] attribute selectors (JS sets these dynamically)
        ],
      }
    }),
    // Minify JS files from public/ folder (Vite copies them as-is by default)
    {
      name: 'minify-public-js',
      async writeBundle() {
        const distDir = resolve(process.cwd(), 'dist')
        const jsFiles = readdirSync(distDir).filter(f => f.endsWith('.js'))
        for (const file of jsFiles) {
          const filePath = join(distDir, file)
          const code = readFileSync(filePath, 'utf-8')
          const result = await minify(code, {
            compress: {
              drop_console: process.env.NODE_ENV !== 'test',
              drop_debugger: true,
            },
            format: { comments: false },
          })
          if (result.code) {
            writeFileSync(filePath, result.code)
            console.log(`✅ Minified public/${file}`)
          }
        }
      }
    },
    // Move language folders from dist/pages/vi/ → dist/vi/ for clean production URLs
    {
      name: 'organize-html-files',
      writeBundle() {
        const distDir = resolve(process.cwd(), 'dist')
        const pagesDir = join(distDir, 'pages')

        if (!existsSync(pagesDir)) return

        const files = readdirSync(pagesDir)
        files.forEach(item => {
          const itemPath = join(pagesDir, item)
          const newPath = join(distDir, item)
          try {
            if (item.endsWith('.html')) {
              renameSync(itemPath, newPath)
              console.log(`✅ Moved ${item} to root`)
            } else if (existsSync(itemPath) && readdirSync(itemPath).length > 0) {
              renameSync(itemPath, newPath)
              console.log(`✅ Moved language folder ${item}/ to root`)
            }
          } catch (err) {
            console.error(`❌ Failed to move ${item}: ${err.message}`)
          }
        })

        try {
          const remaining = readdirSync(pagesDir)
          remaining.forEach(item => {
            const itemPath = join(pagesDir, item)
            if (existsSync(itemPath) && readdirSync(itemPath).length === 0) {
              rmdirSync(itemPath)
            }
          })
          if (readdirSync(pagesDir).length === 0) {
            rmdirSync(pagesDir)
            console.log('✅ Removed empty pages/ directory')
          }
        } catch (err) {
          console.error(`❌ Cleanup error: ${err.message}`)
        }
      }
    },
    // Inline above-the-fold CSS per page and defer the rest (runs last, on the
    // final HTML). Every page except the teleprompter, whose CSS is mostly
    // critical and already prefetched. pruneSource stays off so shared CSS
    // chunks referenced by other pages are never stripped.
    criticalCss({ exclude: ['teleprompter.html'] }),
    // Emit .br + .gz siblings for text assets (runs last, after critical CSS
    // rewrote the HTML). nginx serves them via brotli_static/gzip_static.
    compressAssets(),
  ],
  // JASSUB worker uses ES module syntax — must use 'es' format for worker bundles.
  worker: {
    format: 'es',
  },
  build: {
    outDir: 'dist',
    cssCodeSplit: true,
    assetsInlineLimit: 0, // Disable base64 inline - build all images as files
    minify: 'terser',
    terserOptions: {
      compress: {
        // Keep console.log in test builds, remove in production
        drop_console: process.env.NODE_ENV !== 'test',
        drop_debugger: true,    // Remove debugger statements
        // Only remove console functions in production
        pure_funcs: process.env.NODE_ENV === 'test' ? [] : ['console.log', 'console.info', 'console.debug', 'console.warn']
      },
      format: {
        comments: false         // Remove all comments
      }
    },
    // Enable module preloading for critical JS
    // Automatically inject <link rel="modulepreload"> for dynamic imports
    // CRITICAL: Eliminates waterfall effect, ~200-300ms faster on 3G
    modulePreload: {
      polyfill: true, // Include polyfill for older browsers
      resolveDependencies: (filename, deps, { hostId, hostType }) => {
        return deps;
      }
    },
    rollupOptions: {
      // Build as a multi-page app: include all HTML entries at project root
      input: generateInputEntries(),  // 🚀 Auto-detect all pages + languages
      output: {
        // CSS and other bundled assets go to assets/ with hash
        // Images are handled by vite-plugin-static-copy (preserves structure)
        assetFileNames: (assetInfo) => {
          const info = assetInfo.names?.[0] || assetInfo.fileName || '';

          if (info.endsWith('.css')) {
            return 'assets/[name]-[hash][extname]';
          }

          return 'assets/[name]-[hash][extname]';
        },
        // Ensure HTML files go to dist root, not dist/pages/
        entryFileNames: 'assets/[name]-[hash].js',
        chunkFileNames: 'assets/[name]-[hash].js',
        // Consolidate Firebase into a single shared chunk (avoid duplication)
        manualChunks: (id) => {
          if (id.includes('node_modules/firebase') || id.includes('node_modules/@firebase')) {
            return 'firebase';
          }
        }
      }
    }
  }
})
